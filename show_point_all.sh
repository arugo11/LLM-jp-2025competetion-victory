#!/bin/bash
# chmod +x show_point_all.sh

# 引数がない場合は使い方を表示して終了
if [ "$#" -eq 0 ]; then
    echo "使用法: $0 <ユーザーID1> <ユーザーID2> ..."
    exit 1
fi

# 引数を正規表現の "OR" 形式 (user1|user2|...) に変換
# IFS (内部フィールド区切り文字) を一時的にパイプに変更して結合
USER_REGEX=$(IFS="|"; echo "$*")

# 処理開始のメッセージ（標準エラー出力に出すことで、結果の数値のみをパイプ等で利用可能にする）
echo "集計対象ユーザー: $USER_REGEX" >&2
echo "----------------------------------------" >&2

# 1. show_point を実行
# 2. awk で指定ユーザーを行ごとにマッチングさせて集計
#    - $2 : ユーザーIDの列 (行頭の |- を $1 とみなすため)
#    - $5 : Usedポイントの列
show_point | awk -v regex="^($USER_REGEX)$" '
    # 2列目(ユーザーID)が正規表現に完全一致する場合
    $2 ~ regex {
        # 詳細を標準エラー出力に表示
        printf "%-15s : %10.4f\n", $2, $5 > "/dev/stderr"
        
        # 合計に加算
        sum += $5
    }
    END {
        # 最終的な合計を標準出力に表示
        echo "----------------------------------------" > "/dev/stderr"
        printf "%.4f\n", sum
    }
'